#!/usr/bin/env python3
"""Build source-linked refresh cards without changing canonical notes or questions."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path

from notes_revision import load_notes, apply_study_revision
ROOT = Path(__file__).resolve().parents[1]


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def build_payload() -> dict:
    note_path = ROOT / 'notes/guide.json'
    author_path = ROOT / 'notes/refresh/guide.json'
    notes = load_notes(ROOT)
    author = apply_study_revision(json.loads(author_path.read_text(encoding='utf-8')), 'refresh', ROOT)
    units = {u['id']: (ch, u) for ch in notes['chapters'] for u in ch['units']}
    cards = []
    seen = set()

    def enrich(item: dict) -> None:
        item = dict(item)
        if item['id'] in seen:
            raise ValueError('Duplicate card ID: ' + item['id'])
        seen.add(item['id'])
        refs = item['note_units']
        if not refs or any(uid not in units for uid in refs):
            raise ValueError('Unknown or absent note reference: ' + item['id'])
        for sid in item.get('external_sources', []):
            if sid not in author['external_sources']:
                raise ValueError('Unknown external source: ' + sid)
        item['chapters'] = list(dict.fromkeys(units[uid][0]['id'] for uid in refs))
        item['flags'] = sorted({flag for uid in refs for flag in units[uid][1]['flags']})
        item['source_review_dates'] = list(dict.fromkeys(units[uid][1]['source_review_date'] for uid in refs))
        item['source_hashes'] = {uid: units[uid][1]['body_sha256'] for uid in refs}
        item['edited_at'] = author['edited_at']
        item['review_status'] = 'SOURCE_DERIVED_NOT_INDEPENDENTLY_AUDITED'
        cards.append(item)

    for card in author['cards']:
        enrich({**card, 'deck': 'core'})
    for drug in notes['drugs']:
        # Preserve exact existing names, forms and notes; no invented dose/indication or verification date.
        enrich(dict(id='RF-D-' + drug['id'], title=drug['generic'],
            takeaway=' · '.join(drug['brands']) or '부록에 별도 brand 이름 없음',
            plain=drug['form'], example=drug['notes'], watch=drug['legal_status'],
            note_units=[drug['unit']], stage='product', ra_bridge='',
            external_sources=[], kind='drug-appendix', deck='drugs',
            lookup_url=drug.get('lookup_url'), lookup_label=drug.get('lookup_label'),
            source_ids=drug['source_ids']))
    for chapter in notes['chapters']:
        enrich(dict(id='RF-C-' + chapter['id'],title=chapter['title'],
            takeaway=chapter['summary'],plain='\n'.join(chapter['highlights']),
            example='상세 조건·예외는 아래 연결된 장에서 확인하세요.',
            watch='장 개요입니다. 상세 규칙이나 미확정 적용 관계를 대체하지 않습니다.',
            note_units=[u['id'] for u in chapter['units']],stage='',ra_bridge='',
            external_sources=[],kind='chapter-overview',deck='chapters'))
    for term in author['glossary']:
        if any(uid not in units for uid in term['note_units']):
            raise ValueError('Unknown glossary reference: ' + term['term'])
    for stage in author['stages']:
        if not stage['card_ids'] or any(cid not in seen for cid in stage['card_ids']):
            raise ValueError('Invalid learning path: ' + stage['id'])
    return dict(schema_version='notes-refresh/1',edition=author['edition'],edited_at=author['edited_at'],
        notes_sha256=sha(note_path),authoring_sha256=sha(author_path),notes_revision=author['notes_revision'],cards=cards,
        glossary=author['glossary'],stages=author['stages'],external_sources=author['external_sources'],
        field_checklist=author['field_checklist'],source_policy=author['source_policy'],
        stats=dict(cards=len(cards),curated=sum(c['deck']=='core' for c in cards),
            drugs=sum(c['deck']=='drugs' for c in cards),chapters=sum(c['deck']=='chapters' for c in cards),
            terms=len(author['glossary']),stages=len(author['stages'])))


def outputs() -> dict[Path,str]:
    data = build_payload()
    payload = json.dumps(data,ensure_ascii=False,separators=(',', ':')).replace('</','<\\/')
    manifest = {key:data[key] for key in ['schema_version','edition','edited_at','notes_sha256','authoring_sha256','notes_revision','stats','source_policy']}
    return {
        ROOT/'site/notes/refresh-data.js': '/* Generated by scripts/build_refresh.py. */\nwindow.MPJE_REFRESH = '+payload+';\n',
        ROOT/'site/notes/refresh-build.json': json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',
    }


def main() -> None:
    parser=argparse.ArgumentParser();parser.add_argument('--check', action='store_true');args=parser.parse_args()
    for path,text in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8')!=text:
                raise SystemExit('Stale refresh artifact: '+str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text,encoding='utf-8')
    print(('Checked' if args.check else 'Built')+' source-linked refresh cards; canonical notes/questions unchanged.')

if __name__=='__main__': main()
