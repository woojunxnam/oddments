'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const C=require('../../site/notes/refresh-core.js');
const authored=JSON.parse(fs.readFileSync('notes/refresh/guide.json','utf8'));
const cards=authored.cards.map(c=>({...c,deck:'core',flags:[]}));
const ids=cards.map(c=>c.id), fields=authored.field_checklist.map(f=>f.id);
assert.equal(C.dayKey(new Date('2026-10-28T01:30:00Z')),'2026-10-27');
assert.equal(C.dayKey(new Date('2026-10-28T05:30:00Z')),'2026-10-28');
assert.equal(C.addDays('2026-10-31',3),'2026-11-03'); // crosses US DST boundary
assert.equal(C.addDays('2028-02-28',1),'2028-02-29');
assert.equal(C.validDay('2026-02-30'),false);
assert.equal(C.validDay('not-a-day'),false);
const daily=C.dailyCards(cards,{},'2026-10-27');
assert.equal(daily.length,10);assert.equal(new Set(daily).size,10);
assert.deepEqual(daily,C.dailyCards(cards,{},'2026-10-27'));
assert.notDeepEqual(daily,C.dailyCards(cards,{},'2026-10-28'));
assert.equal(new Set(daily.map(id=>cards.find(c=>c.id===id).stage)).size,7);
const flagged=cards.map(c=>({...c,flags:daily.includes(c.id)?['open']:[]}));
assert(C.dailyCards(flagged,{},'2026-10-27').every(id=>!daily.includes(id)));
const review=C.gradeReview(null,'hard','2026-10-27');
assert.deepEqual(review,{grade:'hard',due:'2026-10-30',last:'2026-10-27',count:1});
assert.equal(C.gradeReview(review,'good','2026-10-27').due,'2026-11-03');
assert.throws(()=>C.gradeReview(null,'mastered','2026-10-27'));
assert.throws(()=>C.cleanState({application:'other',version:1},ids,fields,true));
assert.throws(()=>C.cleanState({application:'oddments-refresh',version:1,reviews:{'RF-001':{grade:'hard',due:'bad',last:'2026-10-27',count:1}}},ids,fields,true));
const cleaned=C.cleanState({saved:['RF-001','RF-001','unknown','__proto__'],field:['license','unknown'],font:999,reviews:{'RF-001':review}},ids,fields);
assert.deepEqual(cleaned.saved,['RF-001']);assert.equal(cleaned.font,24);assert.deepEqual(cleaned.field,['license']);
const before=C.cleanState({saved:['RF-002'],reviews:{'RF-001':review}},ids,fields);
const imported=C.cleanState({saved:['RF-001'],reviews:{'RF-001':{...review,last:'2026-10-20'}}},ids,fields);
const merged=C.mergeState(before,imported);assert.deepEqual(merged.saved,['RF-002','RF-001']);assert.equal(merged.reviews['RF-001'].last,'2026-10-27');
const shuffled=C.shuffled(ids,'seed');assert.equal(new Set(shuffled).size,ids.length);assert.deepEqual(shuffled,C.shuffled(ids,'seed'));assert.notDeepEqual(shuffled,ids);
console.log('PASS: 25 pure scheduling, date, filtering, import and deterministic-shuffle assertions.');
